const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
module.exports=function testExclusiveHelpers(){
  const window={};window.parent=window;
  let personalized=false;
  const audio={src:'',paused:false,loads:0,getAttribute(){return this.src;},pause(){this.paused=true;},load(){this.loads++;},querySelector(){return {src:'https://example.test/demo.mp3'};}};
  const document={querySelector(){return audio;},documentElement:{classList:{contains(){return personalized;}}}};
  const scope=vm.createContext({window,document,location:{search:''},URLSearchParams,structuredClone});
  vm.runInContext(fs.readFileSync(path.join(__dirname,'../public/js/core/theme-runtime.js'),'utf8'),scope);
  scope.NATheme=window.NATheme;
  vm.runInContext(fs.readFileSync(path.join(__dirname,'../public/js/core/exclusive-theme-runtime.js'),'utf8'),scope);
  const helper=window.NAExclusive;
  const first={nodeType:1,textContent:'Nosso'},last={nodeType:1,textContent:'Vinil'};
  const titleHost={childNodes:[first,last]};
  const originalQuery=document.querySelector;document.querySelector=()=>titleHost;
  window.NATheme.styledTitle('.hero-title','Nossa história exclusiva');
  assert.equal(first.textContent+' '+last.textContent,'Nossa história exclusiva');
  window.NATheme.styledTitle('.hero-title','Amor');
  window.NATheme.styledTitle('.hero-title','Nossa nova história');
  assert.equal(first.textContent+' '+last.textContent,'Nossa nova história');document.querySelector=originalQuery;
  const payload={p:{titulo:'Nossa história'},photos:['blob:foto-do-usuario'],videos:['blob:video-do-usuario'],cover:'blob:capa',events:[{titulo:'Nosso encontro',texto:'Uma memória real',data:'2020'}]};
  const base=[{title:'Exemplo',synopsis:'Texto de exemplo',poster:'https://example.test/exemplo.jpg',audio:''}];
  const filled=helper.items(base,undefined,payload,['poster'],true);
  assert.equal(filled[0].title,'Nosso encontro');assert.equal(filled[0].synopsis,'Uma memória real');assert.equal(filled[0].poster,'blob:foto-do-usuario');assert.equal(base[0].title,'Exemplo');
  const override=[{title:'Título editado',poster:'https://example.test/foto.jpg',audio:'https://example.test/faixa.wav'}];
  const customized=helper.items(base,override,payload,['poster'],true);
  assert.equal(customized[0].title,'Título editado');assert.equal(customized[0].poster,override[0].poster);
  assert.equal(helper.stories(payload)[0].video,'blob:video-do-usuario');
  assert.equal(helper.stories({...payload,videos:[]})[0].img,'blob:foto-do-usuario');
  assert.ok(helper.placeholder('<teste>').startsWith('data:image/svg+xml,'));
  assert.equal(helper.asset('javascript:alert(1)'),'');assert.equal(helper.time(8),'0:08');assert.equal(helper.time(125),'2:05');
  const seek={duration:8,currentTime:0};helper.seek(seek,0.5);assert.equal(seek.currentTime,4);helper.seek(seek,2);assert.equal(seek.currentTime,8);
  assert.equal(window.NATheme.selectAudio('https://example.test/primeira.wav'),'https://example.test/primeira.wav');
  const loads=audio.loads;window.NATheme.selectAudio('https://example.test/primeira.wav');assert.equal(audio.loads,loads);
  personalized=true;audio.paused=false;
  assert.equal(window.NATheme.selectAudio(''),'');assert.equal(audio.paused,true,'Faixa vazia não reutiliza a anterior');
};
